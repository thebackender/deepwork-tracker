#!/usr/bin/env python3
"""Deep work tracker.

Usage:
  dw add                           ask for each field
  dw add 90 thesis "Wrote intro"   add a record in one line
  dw stats                         open the statistics page in the browser

Two log files:
  deepwork_logs.md         private, full records. Ignored by git, backed up automatically.
  deepwork_logs.public.md  date + duration only. Generated from deepwork_logs.md; you commit it.

A record's time is the session's start time (now minus the duration).
To fix past records, edit deepwork_logs.md by hand; the next `dw add` or `dw stats`
updates the public file. Commit and push deepwork_logs.public.md yourself.

Backup: when the first record of a new day is added, the private log (every record
from the start up to the last logged day) is copied to
<DW_BACKUP_DIR>/deepwork_logs-YYYY-MM.md, one read-only file per month.
Set DW_BACKUP_DIR in .env (see .env.example); default ~/deepwork-backup.
"""
import json
import os
import re
import stat
import subprocess
import sys
import webbrowser
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LOG_FILE = ROOT / "deepwork_logs.md"            # private: never committed
PUBLIC_FILE = ROOT / "deepwork_logs.public.md"  # public: generated, you commit it
WEB_DIR = ROOT / "web"
GOAL_HOURS = 10_000


def read_env(path):
    """Read KEY=VALUE lines from a .env file. Blank lines and # comments are ignored."""
    values = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip().strip("\"'")
    return values


# Settings come from the environment first, then .env, then the default.
ENV = {**read_env(ROOT / ".env"), **os.environ}
BACKUP_DIR = Path(ENV.get("DW_BACKUP_DIR") or Path.home() / "deepwork-backup").expanduser()


# --- File format --------------------------------------------------------------
# Only read_records(), write_record() and write_public() know the files are
# Markdown tables. To switch formats, rewrite these functions.

HEADER = (
    "# Deep Work Log\n"
    "\n"
    "| Date | Time | Duration | Project | Description |\n"
    "|------|------|----------|---------|-------------|\n"
)
PUBLIC_HEADER = (
    "# Deep Work Log\n"
    "\n"
    "Generated by dw.py from the private log: date and duration (minutes) only.\n"
    "\n"
    "| Date | Duration |\n"
    "|------|----------|\n"
)
CELL_SPLIT = re.compile(r"(?<!\\)\|")  # split on | but not on \|


def read_records():
    """Return all records from the private log, oldest first. Unreadable rows are reported and skipped."""
    if not LOG_FILE.exists():
        return []
    records = []
    lines = LOG_FILE.read_text(encoding="utf-8").splitlines()
    for num, line in enumerate(lines, 1):
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = CELL_SPLIT.split(line)[1:]
        if cells and not cells[-1].strip():
            cells.pop()
        cells = [c.strip() for c in cells]
        if not cells or cells[0] == "Date" or set(cells[0]) <= set("-: "):
            continue  # header or separator row
        try:
            date, time, minutes, project, description = cells
            datetime.strptime(f"{date} {time}", "%Y-%m-%d %H:%M")
            minutes = int(minutes)
            if minutes <= 0:
                raise ValueError
        except ValueError:
            print(f"Skipping line {num} of {LOG_FILE.name}, can't read it: {line}", file=sys.stderr)
            continue
        records.append({
            "date": date,
            "time": time,
            "minutes": minutes,
            "project": project,
            "description": description.replace("\\|", "|"),
        })
    records.sort(key=lambda r: (r["date"], r["time"]))
    return records


def write_record(rec):
    """Append one record to the private log, creating the file with a header if needed."""
    text = LOG_FILE.read_text(encoding="utf-8") if LOG_FILE.exists() else ""
    description = rec["description"].replace("|", "\\|")
    row = f"| {rec['date']} | {rec['time']} | {rec['minutes']} | {rec['project']} | {description} |\n"
    with LOG_FILE.open("a", encoding="utf-8", newline="\n") as f:
        if not text.strip():
            f.write(HEADER)
        elif not text.endswith("\n"):
            f.write("\n")
        f.write(row)


def write_public(records):
    """Regenerate the public file from records. Returns True if its content changed."""
    text = PUBLIC_HEADER + "".join(f"| {r['date']} | {r['minutes']} |\n" for r in records)
    old = PUBLIC_FILE.read_text(encoding="utf-8") if PUBLIC_FILE.exists() else None
    if text == old:
        return False
    with PUBLIC_FILE.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


# --- Public file ----------------------------------------------------------------
# dw only writes the public file. Committing and pushing it is up to you.

def warn_if_private_tracked():
    """Warn if the private log was ever added to git, since it could get published."""
    try:
        result = subprocess.run(["git", "-C", str(ROOT), "ls-files", "--error-unmatch", LOG_FILE.name],
                                capture_output=True, text=True)
    except FileNotFoundError:
        return  # git not installed
    if result.returncode == 0:
        print(f"WARNING: {LOG_FILE.name} is tracked by git, so your private log may get published. "
              f"Remove it with: git rm --cached {LOG_FILE.name}")


def sync_public(records):
    """Regenerate the public file from the private log (e.g. after manual edits)."""
    if not records and not PUBLIC_FILE.exists():
        return  # nothing logged yet
    write_public(records)
    warn_if_private_tracked()


# --- Monthly backup of the private log -----------------------------------------
# Taken when the first record of a new day is added. At that moment the log holds
# every record from the start up to the last logged day, so the backup never
# contains today's (possibly unfinished) day. The file is named after the month of
# its latest record: the current month's file is replaced on each new day, and once
# the month is over its file stays final. Files are read-only to prevent accidental edits.

READ_ONLY = stat.S_IREAD | stat.S_IRGRP | stat.S_IROTH


def backup(latest_date):
    """Copy the private log to BACKUP_DIR/deepwork_logs-YYYY-MM.md. Reports errors instead of raising."""
    path = BACKUP_DIR / f"deepwork_logs-{latest_date[:7]}.md"
    try:
        BACKUP_DIR.mkdir(parents=True, exist_ok=True)
        data = LOG_FILE.read_bytes()
        if path.exists():
            path.chmod(stat.S_IREAD | stat.S_IWRITE)  # unlock to replace it
        path.write_bytes(data)
        path.chmod(READ_ONLY)
        if path.read_bytes() != data:
            raise OSError(f"{path} doesn't match the log after copying")
        print(f"Backup: {path} (records up to {latest_date})")
    except OSError as e:
        print(f"Backup failed: {e}")


# --- Commands -------------------------------------------------------------------

def parse_minutes(text):
    try:
        minutes = int(text)
    except ValueError:
        raise ValueError(f"Duration must be whole minutes, got {text!r}") from None
    if not 0 < minutes <= 24 * 60:
        raise ValueError("Duration must be between 1 and 1440 minutes")
    return minutes


def check_project(text):
    project = text.strip()
    if not project or "|" in project:
        raise ValueError("Project can't be empty or contain |")
    return project


def recent_projects(records):
    """Projects ordered by most recent use."""
    projects = []
    for r in reversed(records):
        if r["project"] not in projects:
            projects.append(r["project"])
    return projects


def ask(prompt, check, default=""):
    while True:
        suffix = f" [{default}]" if default else ""
        value = input(f"{prompt}{suffix}: ").strip() or default
        try:
            return check(value)
        except ValueError as e:
            print(e)


def cmd_add(args):
    records = read_records()
    if args and len(args) < 3:
        sys.exit('Usage: dw add <minutes> <project> "<description>"   (or just: dw add)')
    if args:
        try:
            minutes = parse_minutes(args[0])
            project = check_project(args[1])
        except ValueError as e:
            sys.exit(str(e))
        description = " ".join(args[2:]).strip()
    else:
        projects = recent_projects(records)
        minutes = ask("Duration (min)", parse_minutes)
        if projects:
            print("Projects:", ", ".join(projects[:10]))
        project = ask("Project", check_project, projects[0] if projects else "")
        description = input("Description: ").strip()

    start = datetime.now() - timedelta(minutes=minutes)
    rec = {
        "date": start.strftime("%Y-%m-%d"),
        "time": start.strftime("%H:%M"),
        "minutes": minutes,
        "project": project,
        "description": description,
    }
    latest_date = max((r["date"] for r in records), default=None)
    if latest_date and rec["date"] > latest_date:
        backup(latest_date)  # first record of a new day: save everything before it
    write_record(rec)
    sync_public(read_records())

    done = (sum(r["minutes"] for r in records) + minutes) / 60
    left = max(0, GOAL_HOURS - done)
    print(f"Saved: {rec['date']} {rec['time']} | {minutes} min | {project} | {description}")
    print(f"Total: {done:,.1f} h done, {left:,.1f} h left to {GOAL_HOURS:,}")


def write_data_js(records):
    """Export records as JSON for the browser (pages opened from disk can't read files)."""
    data = {
        "goalHours": GOAL_HOURS,
        "generated": datetime.now().isoformat(timespec="minutes"),
        "records": records,
    }
    path = WEB_DIR / "data.js"
    path.write_text("window.DEEPWORK = " + json.dumps(data, ensure_ascii=False) + ";\n",
                    encoding="utf-8")


def cmd_stats():
    records = read_records()
    sync_public(records)
    write_data_js(records)
    page = WEB_DIR / "index.html"
    webbrowser.open(page.as_uri())
    print(f"Opened {page} ({len(records)} records)")


def main():
    args = sys.argv[1:]
    if not args or args[0] in ("-h", "--help", "help"):
        print(__doc__)
        return
    command, rest = args[0], args[1:]
    if command == "add":
        cmd_add(rest)
    elif command == "stats":
        cmd_stats()
    else:
        sys.exit(f"Unknown command: {command}\n{__doc__}")


if __name__ == "__main__":
    try:
        main()
    except (KeyboardInterrupt, EOFError):
        sys.exit("\nCancelled.")
